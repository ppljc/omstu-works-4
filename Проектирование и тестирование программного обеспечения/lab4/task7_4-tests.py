import pytest
from task7_4 import find_closest_team_sums


@pytest.mark.parametrize(
    "weights, expected",
    [
        # 1. Простые случаи
        ([1, 2], (1, 2)),                    # 1 vs 2
        ([1, 1], (1, 1)),                    # равные суммы
        ([1, 3, 4], (4, 4)),                 # 1+3=4 и 4
        ([5, 5, 5, 5], (10, 10)),            # идеальное разбиение

        # 2. Классический пример из предыдущего объяснения
        ([1, 2, 3, 6], (5, 7)),              # 2+3=5  и  1+6=7

        # 3. Нечётное количество участников
        ([1, 2, 3], (3, 3)),                 # 3 vs 1+2=3
        ([10, 20, 30], (30, 30)),            # 30 vs 10+20=30
        ([1, 1, 1], (1, 2)),                 # 1 vs 1+1=2

        # 4. Все веса одинаковые
        ([7, 7, 7, 7, 7], (14, 21)),         # 2 vs 3 человека

        # 5. Один большой вес
        ([1, 1, 1, 100], (2, 101)),          # 1+1=2 и 100+1=101
        ([50, 1, 2, 3], (5, 51)),            # 2+3=5 и 50+1=51

        # 6. Случаи, где оптимально брать разные комбинации
        ([1, 5, 6, 7], (8, 11)),             # 1+7=8  и  5+6=11  → ближе 8 и 11
        ([4, 5, 6, 7], (11, 11)),            # 4+7=11 и 5+6=11

        # 7. Минимальные и граничные случаи
        ([], (0, 0)),                        # пустой список
        ([42], (0, 42)),                     # один человек → одна команда пустая
        ([10, 10], (10, 10)),

        # 8. Более сложные тесты
        ([1, 2, 3, 4, 5], (7, 8)),           # 2+5=7 и 1+3+4=8
        ([9, 8, 7, 6, 5, 4], (19, 20)),      # например 9+6+4=19 и 8+7+5=20
        ([2, 3, 5, 7, 11, 13], (20, 21)),    # 13+7=20 и 11+5+3+2=21
    ]
)
def test_find_closest_team_sums(weights, expected):
    result = find_closest_team_sums(weights)
    assert result == expected, f"Для весов {weights} ожидалось {expected}, получено {result}"
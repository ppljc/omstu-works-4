import pytest
from task2_4 import *


@pytest.mark.parametrize("combinations, tricks, expected_indices", [
    # Тест 1: Две комбинации, обе выполняются
    (
            [
                [0, 1, 3, 2, 4],
                [1, 0, 3, 4, 2]
            ],
            [0, 1],
            [1, 0, 2, 4, 3]
    ),

    # Тест 2: Одна комбинация, сдвиг первой карты в конец
    (
            [
                [1, 2, 3, 4, 0]
            ],
            [0],
            [1, 2, 3, 4, 0]
    ),

    # Тест 3: Последовательное применение 3-х разных трюков
    (
            [
                [1, 0, 2, 3, 4],
                [0, 2, 1, 3, 4],
                [0, 1, 3, 2, 4]
            ],
            [0, 1, 2],
            [1, 2, 3, 0, 4]
    ),

    # Тест 4: Повторяющиеся трюки (1, 2, 1)
    (
            [
                [0, 1, 2, 3, 4],
                [1, 0, 2, 3, 4]
            ],
            [0, 1, 0],
            [1, 0, 2, 3, 4]
    ),

    # Тест 5: Полный реверс колоды + сдвиг
    (
            [
                [4, 3, 2, 1, 0],
                [4, 0, 1, 2, 3]
            ],
            [0, 1, 1, 1, 0],
            [3, 4, 0, 1, 2]
    )
])
def test_calculate(combinations, tricks, expected_indices):
    result = calculate(combinations, tricks)
    assert result == expected_indices
